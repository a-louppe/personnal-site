/**
 * The single source of truth for colour (CLAUDE.md rule 3).
 *
 * Every dithered world uses four roles, dark to light: void, shade, signal, light.
 * Components and shaders use roles, never raw hex values, so a world is just a
 * set of values for those roles. See the "Design system" tab of the project doc.
 */

export type Hex = `#${string}`;

export const ROLES = ['void', 'shade', 'signal', 'light'] as const;
export type Role = (typeof ROLES)[number];
export type RolePalette = Readonly<Record<Role, Hex>>;

/** The violet occult collage: the dialogue past the end of the scroll. */
export const THRESHOLD: RolePalette = {
  void: '#0b0708',
  shade: '#3b2a4c',
  signal: '#52a0b8',
  light: '#d8b0a2',
};

/** The red dither cathedral: the boss fight. Andrey's reference, do not change. */
export const CATHEDRAL: RolePalette = {
  void: '#0d0000',
  shade: '#5c0f1c',
  signal: '#c41634',
  light: '#ecb27c',
};

/**
 * Colours outside the four roles. They never enter the dither pass: they are for
 * HTML overlay text and ornaments only.
 */
export const EXTRAS = {
  /** Long text in both worlds. */
  bone: '#ece4df',
  /** 4-point sparkles and the sword glint only. Never text. */
  sparkle: '#ffffff',
  /** Quiet UI: menus, stripes. */
  mist: '#9baeb0',
  /** Posterized midtone of the collage. Shapes only, never text. */
  violetMid: '#5f4174',
  /** The collage's echo lines. Text at 18px or more on void only. */
  tealDim: '#637e86',
  /** Small crimson text on void (AA 4.8:1), where #c41634 would fail. */
  crimsonText: '#e0405a',
} as const satisfies Record<string, Hex>;

type Lab = readonly [number, number, number];

function toLinear(channel: number): number {
  const c = channel / 255;
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
}

function toSrgbByte(linear: number): number {
  const c = Math.min(1, Math.max(0, linear));
  const v = c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055;
  return Math.round(v * 255);
}

function hexToOklab(hex: Hex): Lab {
  const n = Number.parseInt(hex.slice(1), 16);
  const r = toLinear((n >> 16) & 255);
  const g = toLinear((n >> 8) & 255);
  const b = toLinear(n & 255);
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
}

function oklabToHex([L, a, b]: Lab): Hex {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const bytes = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ].map(toSrgbByte);
  return `#${bytes.map((v) => v.toString(16).padStart(2, '0')).join('')}`;
}

/** Mix two colours in OKLab. t = 0 gives `from`, t = 1 gives `to`. */
export function mixOklab(from: Hex, to: Hex, t: number): Hex {
  const a = hexToOklab(from);
  const b = hexToOklab(to);
  return oklabToHex([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t]);
}

/** Number of palette steps in the descent, Threshold (0) to Cathedral (last). */
export const DESCENT_STEP_COUNT = 5;

/**
 * The descent palette for a progress between 0 (Threshold) and 1 (Cathedral).
 * It is quantized to hard steps on purpose: pixel art swaps palettes, it never
 * fades between them.
 */
export function descentPalette(progress: number): RolePalette {
  const clamped = Math.min(1, Math.max(0, progress));
  const last = DESCENT_STEP_COUNT - 1;
  const t = Math.round(clamped * last) / last;
  return Object.fromEntries(
    ROLES.map((role) => [role, mixOklab(THRESHOLD[role], CATHEDRAL[role], t)]),
  ) as Record<Role, Hex>;
}

/** All descent steps, precomputed. */
export const DESCENT: readonly RolePalette[] = Array.from({ length: DESCENT_STEP_COUNT }, (_, i) =>
  descentPalette(i / (DESCENT_STEP_COUNT - 1)),
);

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

/**
 * The CSS custom properties the site's tokens file is generated from.
 * `--world-*` are the role tokens components use; a `[data-world]` scope swaps them.
 */
export function cssTokens(): string {
  const lines: string[] = [
    '/* Generated by scripts/gen-tokens.mjs from packages/dither/src/palettes.ts. Do not edit. */',
    ':root {',
  ];
  for (const role of ROLES) lines.push(`  --threshold-${role}: ${THRESHOLD[role]};`);
  for (const role of ROLES) lines.push(`  --cathedral-${role}: ${CATHEDRAL[role]};`);
  for (const [name, hex] of Object.entries(EXTRAS)) lines.push(`  --${kebab(name)}: ${hex};`);
  lines.push('}', '');
  const scope = (selector: string, palette: RolePalette) => {
    lines.push(`${selector} {`);
    for (const role of ROLES) lines.push(`  --world-${role}: ${palette[role]};`);
    lines.push('}', '');
  };
  scope('[data-world="threshold"]', THRESHOLD);
  DESCENT.slice(1, -1).forEach((palette, i) => scope(`[data-world="descent-${i + 1}"]`, palette));
  scope('[data-world="cathedral"]', CATHEDRAL);
  return lines.join('\n');
}
